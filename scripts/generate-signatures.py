#!/usr/bin/env python3
"""
Generates the film-grain tile and one Chladni figure per pitched preset, plus
the lib/toneSignatures.ts registry that requires them. Standard library only.

A square plate driven at mode (n, m) settles sand along the zero lines of
    cos(n*pi*x) * cos(m*pi*y) - cos(m*pi*x) * cos(n*pi*y)
and the plate's frequency rises with n^2 + m^2. So presets take modes in pitch
order: a higher tone really does get a denser figure, and the mapping is stable.
These are illustrations of the maths, not a measurement of the sound.

Usage: python scripts/generate-signatures.py
"""

import math
import random
import re
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'assets' / 'images' / 'art' / 'signatures'
SIZE = 384
LINE = 0.055


def write_gray_alpha_png(path, size, pixels):
    """pixels: size*size (luminance, alpha) byte pairs, row by row."""
    raw = bytearray()
    for y in range(size):
        raw.append(0)
        raw += pixels[y * size * 2:(y + 1) * size * 2]

    def chunk(kind, data):
        body = kind + data
        return struct.pack('>I', len(data)) + body + struct.pack('>I', zlib.crc32(body))

    path.write_bytes(
        b'\x89PNG\r\n\x1a\n'
        + chunk(b'IHDR', struct.pack('>IIBBBBB', size, size, 8, 4, 0, 0, 0))
        + chunk(b'IDAT', zlib.compress(bytes(raw), 9))
        + chunk(b'IEND', b'')
    )


def modes():
    pairs = [(n, m) for n in range(1, 13) for m in range(n + 1, 14) if n * n + m * m >= 13]
    return sorted(pairs, key=lambda p: (p[0] ** 2 + p[1] ** 2, p[0]))


def figure(n, m):
    cos_n = [math.cos(n * math.pi * i / (SIZE - 1)) for i in range(SIZE)]
    cos_m = [math.cos(m * math.pi * i / (SIZE - 1)) for i in range(SIZE)]
    centre = (SIZE - 1) / 2
    pixels = bytearray(SIZE * SIZE * 2)
    for y in range(SIZE):
        for x in range(SIZE):
            value = cos_n[x] * cos_m[y] - cos_m[x] * cos_n[y]
            line = math.exp(-((value / LINE) ** 2))
            # Fades out before the edge, so it never reads as a square pasted
            # on top of the artwork.
            radius = math.hypot(x - centre, y - centre) / centre
            mask = max(0.0, min(1.0, (1.0 - radius) / 0.25))
            at = (y * SIZE + x) * 2
            pixels[at] = 255
            pixels[at + 1] = int(255 * line * mask)
    return pixels


def grain():
    rng = random.Random(852)
    size = 96
    pixels = bytearray(size * size * 2)
    for i in range(size * size):
        # Equal parts lighter and darker, so the tile adds texture without
        # shifting the artwork's overall brightness.
        pixels[i * 2] = 255 if rng.random() < 0.5 else 0
        pixels[i * 2 + 1] = rng.randrange(256)
    write_gray_alpha_png(ROOT / 'assets' / 'images' / 'art' / 'grain.png', size, pixels)


def pitched_presets():
    source = (ROOT / 'lib' / 'frequencies.ts').read_text(encoding='utf-8')
    found = []
    for block in re.split(r"\n\s*\{\n", source):
        ident = re.search(r"id: '((?:binaural|solfeggio)-[^']+)'", block)
        if not ident:
            continue
        key = 'beatFrequency' if ident.group(1).startswith('binaural') else 'frequency'
        hz = re.search(key + r": ([\d.]+)", block)
        found.append((float(hz.group(1)), ident.group(1)))
    return sorted(found)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    grain()
    presets = pitched_presets()
    assert len(presets) == len({p[1] for p in presets}) and presets, 'preset parse failed'
    available = modes()
    # Every third mode: neighbours in the list look nearly identical.
    chosen = available[::3][: len(presets)]
    assert len(chosen) == len(presets), 'not enough modes'
    rows = []
    for (hz, ident), (n, m) in zip(presets, chosen):
        write_gray_alpha_png(OUT / f'{ident}.png', SIZE, figure(n, m))
        rows.append(f"  '{ident}': require('@/assets/images/art/signatures/{ident}.png'),")
        print(ident, hz, (n, m))
    (ROOT / 'lib' / 'toneSignatures.ts').write_text(
        "// Generated by scripts/generate-signatures.py. Do not edit by hand.\n"
        "import type { ImageSourcePropType } from 'react-native';\n\n"
        "const SIGNATURES: Record<string, ImageSourcePropType> = {\n"
        + '\n'.join(rows)
        + "\n};\n\n"
        "/** The preset's Chladni figure; noise has no single pitch, so none. */\n"
        "export function toneSignature(id: string): ImageSourcePropType | undefined {\n"
        "  return SIGNATURES[id];\n"
        "}\n",
        encoding='utf-8',
    )


if __name__ == '__main__':
    main()
